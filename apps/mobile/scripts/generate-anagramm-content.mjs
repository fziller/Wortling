#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptDir, "..");
const outputPath = path.join(appDir, "src/games/anagramm/generated/content.ts");
const inputs = {
  4: { targets: "src/games/wortleiter/generated/targetWords.ts", erweitert: "src/games/wortleiter/generated/erweitertWords.ts", hart: "src/games/wortleiter/generated/hartWords.ts", allowed: "src/games/wortleiter/generated/allowedGuesses.ts" },
  5: { targets: "src/games/between/generated/targetWords.ts", erweitert: "src/games/between/generated/erweitertWords.ts", hart: "src/games/between/generated/hartWords.ts", allowed: "src/games/between/generated/allowedGuesses.ts" },
  6: { targets: "src/games/wortcode/generated/targetWords.ts", erweitert: "src/games/wortcode/generated/erweitertWords.ts", hart: "src/games/wortcode/generated/hartWords.ts", allowed: "src/games/wortcode/generated/allowedGuesses.ts" },
  7: { targets: "src/games/shared/generated/targetWords7.ts", erweitert: "src/games/shared/generated/erweitertWords7.ts", hart: "src/games/shared/generated/hartWords7.ts", allowed: "src/games/shared/generated/allowedGuesses7.ts" },
  8: { targets: "src/games/wabenwort/generated/8/targetWords.ts", erweitert: "src/games/wabenwort/generated/8/erweitertWords.ts", hart: "src/games/wabenwort/generated/8/hartWords.ts", allowed: "src/games/wabenwort/generated/8/allowedGuesses.ts" },
};

function parseGeneratedArray(fileText) {
  const match = fileText.match(/= (\[[\s\S]*?\]) as const/);
  if (!match) throw new Error("Generated word array not found.");
  return JSON.parse(match[1]);
}

function normalize(word) {
  return word.normalize("NFC").trim().toLocaleLowerCase("de-DE");
}

function signature(word) {
  return Array.from(normalize(word)).sort(new Intl.Collator("de-DE").compare).join("");
}

const targetsByLength = {};
const targetsByPreset = { klassisch: {}, erweitert: {}, hart: {} };
const solutionsBySignature = {};

for (const [length, paths] of Object.entries(inputs)) {
  const [targets, erweitert, hart, allowed] = await Promise.all([
    readFile(path.join(appDir, paths.targets), "utf8").then(parseGeneratedArray),
    readFile(path.join(appDir, paths.erweitert), "utf8").then(parseGeneratedArray),
    readFile(path.join(appDir, paths.hart), "utf8").then(parseGeneratedArray),
    readFile(path.join(appDir, paths.allowed), "utf8").then(parseGeneratedArray),
  ]);
  const normalizedTargets = [...new Set(targets.map(normalize))].filter((word) => Array.from(word).length === Number(length));
  const targetSignatures = new Set(normalizedTargets.map(signature));
  const groups = new Map();
  for (const word of allowed.map(normalize)) {
    if (Array.from(word).length !== Number(length)) continue;
    const key = signature(word);
    if (!targetSignatures.has(key)) continue;
    groups.set(key, [...(groups.get(key) ?? []), word]);
  }
  targetsByLength[length] = normalizedTargets;
  targetsByPreset.klassisch[length] = normalizedTargets;
  targetsByPreset.erweitert[length] = [...new Set(erweitert.map(normalize))].filter((word) => Array.from(word).length === Number(length));
  targetsByPreset.hart[length] = [...new Set(hart.map(normalize))].filter((word) => Array.from(word).length === Number(length));
  solutionsBySignature[length] = Object.fromEntries(
    [...groups.entries()].map(([key, words]) => [key, [...new Set(words)].sort(new Intl.Collator("de-DE").compare)]),
  );
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
    `// Generated by scripts/generate-anagramm-content.mjs. Do not edit by hand.\n` +
    `export const generatedAnagrammTargetsByLength = ${JSON.stringify(targetsByLength, null, 2)} as const;\n` +
    `export const generatedAnagrammTargetsByPreset = ${JSON.stringify(targetsByPreset, null, 2)} as const;\n` +
    `export const generatedAnagrammSolutionsBySignature = ${JSON.stringify(solutionsBySignature, null, 2)} as const;\n`,
  "utf8",
);
console.log(`Generated Anagramm content at ${path.relative(process.cwd(), outputPath)}.`);
