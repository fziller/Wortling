import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { classifyBucket } from "./pipeline/shared.mjs";
import { fetchBioWords } from "./sources/bio.mjs";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptDir, "..");
const args = new Map(process.argv.slice(2).map((arg) => {
  const [key, value = ""] = arg.replace(/^--/, "").split("=");
  return [key, value];
}));

const outputPath = path.resolve(appDir, args.get("output") ?? "src/games/packs/bio/generated/bioTargets.ts");
const supportedLengths = [4, 5, 6, 7];

const collator = new Intl.Collator("de-DE", { sensitivity: "base" });

const byLength = { 4: [], 5: [], 6: [], 7: [] };
const allowedByLength = { 4: [], 5: [], 6: [], 7: [] };

for (const len of supportedLengths) {
  const raws = await fetchBioWords(len);
  const words = new Set();
  const wordTags = new Map();
  for (const r of raws) {
    const w = r.form;
    words.add(w);
    if (!wordTags.has(w)) wordTags.set(w, new Set());
    wordTags.get(w).add(r.tag);
  }
  // Filter genitive (shouldn't happen for BIO:BASE, but keep pipeline consistent)
  const filtered = [...words].filter((w) => {
    const tags = wordTags.get(w);
    const bucket = classifyBucket(w, tags);
    return bucket !== "genitive";
  });
  filtered.sort(collator.compare);
  byLength[len] = filtered;
  allowedByLength[len] = [...filtered]; // for bio, allowed == targets (no zipf distinction)
}

await mkdir(path.dirname(outputPath), { recursive: true });

// Emit single file with all lengths
const content =
  `// Generated by scripts/import-bio-words.mjs. Do not edit by hand.\n` +
  `// Source: scripts/data/bio.tsv + Wikidata (best-effort). No Zipf — all valid shapes are targets (genitive excluded).\n` +
  `export const bioTargetWordsByLength = ${JSON.stringify(byLength, null, 2)} as const;\n` +
  `export const bioAllowedWordsByLength = ${JSON.stringify(allowedByLength, null, 2)} as const;\n` +
  `// Flat helpers per length for convenience\n` +
  `export const bioTargetWords4 = bioTargetWordsByLength[4] as unknown as string[];\n` +
  `export const bioTargetWords5 = bioTargetWordsByLength[5] as unknown as string[];\n` +
  `export const bioTargetWords6 = bioTargetWordsByLength[6] as unknown as string[];\n` +
  `export const bioTargetWords7 = bioTargetWordsByLength[7] as unknown as string[];\n`;

await writeFile(outputPath, content, "utf8");

for (const len of supportedLengths) {
  console.log(`Bio length ${len}: ${byLength[len].length} words -> ${path.relative(process.cwd(), outputPath)}`);
}
console.log(`Generated bio pack at ${path.relative(process.cwd(), outputPath)}`);
