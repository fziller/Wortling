#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptDir, "..");
const outputPath = path.join(appDir, "src/games/wortschmelze/generated/puzzles.ts");
const collator = new Intl.Collator("de-DE", { sensitivity: "base" });

const inputs = {
  klassisch: "src/games/between/generated/targetWords.ts",
  erweitert: "src/games/between/generated/erweitertWords.ts",
  hart: "src/games/between/generated/hartWords.ts",
};

const BLOCKED_COMPONENTS = new Set([
  "admin", "alien", "audio", "award", "bacon", "basic", "comic", "crash", "flash", "flush",
  "happy", "image", "intro", "joker", "laser", "level", "login", "party", "pixel", "radio",
  "robot", "shake", "shirt", "smart", "sport", "story", "super", "team", "video",
]);

function parseGeneratedArray(fileText) {
  const match = fileText.match(/= (\[[\s\S]*?\]) as const/);
  if (!match) throw new Error("Generated word array not found.");
  return JSON.parse(match[1]);
}

function lengthOf(word) {
  return Array.from(word).length;
}

function sliceLetters(word, start, end) {
  return Array.from(word).slice(start, end).join("");
}

function buildPuzzles(words) {
  const cleanWords = [...new Set(words)]
    .filter((word) => lengthOf(word) === 5 && !BLOCKED_COMPONENTS.has(word))
    .sort(collator.compare);
  const byPrefix = new Map();

  for (const word of cleanWords) {
    const prefix = sliceLetters(word, 0, 2);
    byPrefix.set(prefix, [...(byPrefix.get(prefix) ?? []), word]);
  }

  const seen = new Set();
  const puzzles = [];

  for (const left of cleanWords) {
    const overlap = sliceLetters(left, -2);
    for (const right of byPrefix.get(overlap) ?? []) {
      if (left === right) continue;
      const answer = left + sliceLetters(right, 2);
      if (lengthOf(answer) !== 8 || seen.has(answer)) continue;
      seen.add(answer);
      puzzles.push({ answer, left, right, overlap });
    }
  }

  return puzzles.sort((a, b) => collator.compare(a.answer, b.answer) || collator.compare(a.left, b.left) || collator.compare(a.right, b.right));
}

const output = {};

for (const [preset, relPath] of Object.entries(inputs)) {
  const words = parseGeneratedArray(await readFile(path.join(appDir, relPath), "utf8"));
  output[preset] = buildPuzzles(words);
}

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate-wortschmelze-puzzles.mjs. Do not edit by hand.\n` +
    `// 5+5 word merges where the first word's last two letters match the second word's first two letters.\n` +
    `export const generatedWortschmelzePuzzles = ${JSON.stringify(output, null, 2)} as const;\n`,
  "utf8",
);

console.log(`Generated Wortschmelze puzzles at ${path.relative(process.cwd(), outputPath)}.`);
for (const [preset, puzzles] of Object.entries(output)) {
  console.log(`  ${preset}: ${puzzles.length}`);
}
